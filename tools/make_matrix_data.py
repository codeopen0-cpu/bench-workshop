"""Turns the UNO R4 WiFi LED matrix's upstream data into the app's data files:

    python tools/make_matrix_data.py

  tools/vendor/ledmatrix/gallery.h            (Arduino_LED_Matrix, ArduinoCore-renesas: MIT)
      -> src/sketch/ledmatrix-gallery.ts       LEDMATRIX_* pictures and animations
  tools/vendor/ledmatrix/Font_4x6.c, Font_5x7.c (ArduinoGraphics: MPL-2.0)
      -> src/sketch/ledmatrix-fonts.ts         the two fonts (that file stays MPL-2.0)

The sources are copied as they are from GitHub (arduino/ArduinoCore-renesas
libraries/Arduino_LED_Matrix/src, arduino-libraries/ArduinoGraphics src), so a newer
version only needs copying in and this run again.
"""
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
VENDOR = ROOT / 'tools' / 'vendor' / 'ledmatrix'


def gallery():
    text = (VENDOR / 'gallery.h').read_text(encoding='utf-8')
    out = {}
    # single pictures: constexpr uint32_t NAME[] = { a, b, c, ms };
    for m in re.finditer(r'constexpr\s+uint32_t\s+(\w+)\[\]\s*=\s*\{([^{}]*)\};', text):
        out[m.group(1)] = [int(x, 0) for x in m.group(2).replace(' ', '').split(',') if x]
    # animations: constexpr uint32_t NAME[][4] = { { a, b, c, ms }, ... };
    for m in re.finditer(r'constexpr\s+uint32_t\s+(\w+)\[\]\[4\]\s*=\s*\{(.*?)\n\};', text, re.S):
        frames = re.findall(r'\{([^{}]*)\}', m.group(2))
        out[m.group(1)] = [[int(x, 0) for x in f.replace(' ', '').replace('\t', '').split(',') if x.strip()] for f in frames]
    return out


def font(name):
    text = (VENDOR / f'{name}.c').read_text(encoding='utf-8')
    head = re.search(r'const struct Font ' + name + r'\s*=\s*\{\s*(\d+),\s*(\d+),\s*\(const uint8_t\*\[\]\)\{', text)
    w, h = int(head.group(1)), int(head.group(2))
    body = text[head.end():]
    glyphs = []
    i = 0
    # entries in order (char 0, 1, 2...): NULL, or (const uint8_t[]){ rows }
    for m in re.finditer(r'NULL|\(const uint8_t\[\]\)\{([^}]*)\}', body):
        if m.group(0) == 'NULL':
            glyphs.append(None)
        else:
            rows = [int(x.strip(), 0) for x in m.group(1).split(',') if x.strip() and not x.strip().startswith('//')]
            rows = [int(re.sub(r'//.*', '', x).strip(), 0) for x in m.group(1).split('\n') if re.sub(r'//.*', '', x).strip(' ,\t\r')] if not rows else rows
            glyphs.append(rows)
        i += 1
    return {'w': w, 'h': h, 'glyphs': glyphs}


def main():
    g = gallery()
    lines = ['// Generated by tools/make_matrix_data.py from Arduino_LED_Matrix\'s gallery.h',
             '// (arduino/ArduinoCore-renesas, MIT): the UNO R4 WiFi\'s built-in pictures and animations.',
             '// Each picture: 3 words of LED bits (LED 0 = the top word\'s top bit, row by row, 12 per row)',
             '// and how long it shows (ms); an animation: a list of those.',
             'export const LEDMATRIX_GALLERY: Record<string, number[] | number[][]> = ' + json.dumps(g, separators=(',', ':')) + ';', '']
    (ROOT / 'src' / 'sketch' / 'ledmatrix-gallery.ts').write_text('\n'.join(lines), encoding='utf-8')
    fonts = {n: font(n) for n in ('Font_4x6', 'Font_5x7')}
    for n, f in fonts.items():
        drawn = sum(1 for x in f['glyphs'] if x)
        bad = [i for i, x in enumerate(f['glyphs']) if x and len(x) != f['h']]
        print(f'{n}: {f["w"]}x{f["h"]}, {len(f["glyphs"])} codes, {drawn} drawn, wrong heights: {bad[:5]}')
        assert not bad and drawn > 90
    lines = ['/* This Source Code Form is subject to the terms of the Mozilla Public License, v. 2.0.',
             ' * If a copy of the MPL was not distributed with this file, You can obtain one at https://mozilla.org/MPL/2.0/.',
             ' * The fonts of the ArduinoGraphics library (arduino-libraries/ArduinoGraphics, Copyright (c) Arduino SA),',
             ' * converted by tools/make_matrix_data.py: glyphs[char] = its rows, top first, leftmost dot = bit 7. */',
             'export const MATRIX_FONTS: Record<string, { w: number; h: number; glyphs: (number[] | null)[] }> = ' + json.dumps(fonts, separators=(',', ':')) + ';', '']
    (ROOT / 'src' / 'sketch' / 'ledmatrix-fonts.ts').write_text('\n'.join(lines), encoding='utf-8')
    pics = [k for k, v in g.items() if not isinstance(v[0], list)]
    anims = [k for k, v in g.items() if isinstance(v[0], list)]
    print(f'gallery: {len(pics)} pictures, {len(anims)} animations ({", ".join(f"{k} {len(g[k])}" for k in anims)})')
    assert g['LEDMATRIX_HEART_BIG'] == [0x3184a444, 0x44042081, 0x100a0040, 66]


main()
